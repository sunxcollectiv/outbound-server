"""Seed the areas table with ~1000 curated cities/towns, each linked to its
parent country/territory area via ``parent_id``.

Run it any time — idempotent. City areas are matched on (name, parent_id) so the
same-named cities in different countries (Córdoba in Spain and Argentina, San
Jose in the US and Costa Rica) both exist and stay distinct:

    uv run python -m app.seeds.cities

Parents are the country/territory areas from app.seeds.countries, looked up by
name, so run (or let this run) the countries seed first. The city list itself
lives in app.seeds._cities_data (generated by scripts/generate_cities.py).
"""
from __future__ import annotations

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.db import SessionLocal
from app.models import Area
from app.seeds import countries
from app.seeds._cities_data import CITIES


def seed_cities(session: Session) -> dict[str, int]:
    """Insert any missing city areas, linked to their parent country/territory.
    Idempotent; returns counts. Cities whose parent area is missing are skipped
    and counted under ``unresolved``."""
    parents = {
        name.casefold(): area_id
        for area_id, name in session.execute(
            select(Area.id, Area.name).where(Area.kind.in_(("country", "territory")))
        ).all()
    }
    existing = {
        (name.casefold(), parent_id)
        for name, parent_id in session.execute(
            select(Area.name, Area.parent_id).where(Area.kind == "city")
        ).all()
    }

    created = 0
    unresolved = 0
    for city, country in CITIES:
        parent_id = parents.get(country.casefold())
        if parent_id is None:
            unresolved += 1
            continue
        key = (city.casefold(), parent_id)
        if key in existing:
            continue
        session.add(Area(name=city, kind="city", parent_id=parent_id))
        existing.add(key)
        created += 1

    session.commit()
    total = len(CITIES)
    return {
        "created": created,
        "skipped": total - created - unresolved,
        "unresolved": unresolved,
        "total": total,
    }


def main() -> None:
    with SessionLocal() as session:
        # Parents must exist first; seeding countries is itself idempotent.
        countries.seed_areas(session)
        result = seed_cities(session)
    msg = (
        f"Seeded cities: created {result['created']}, "
        f"skipped {result['skipped']} already present "
        f"(of {result['total']} in the list)."
    )
    if result["unresolved"]:
        msg += f" {result['unresolved']} skipped — parent country not found."
    print(msg)


if __name__ == "__main__":
    main()
