"""Generate app/seeds/_airport_google_ids.py — which Google place each seeded
airport is, so a new server's seed links them without searching Google again.

    uv run python scripts/export_airport_google_ids.py

Reads the airports (category "airport", with a code and a google_place_id) from
DATABASE_URL — the database where scripts/link_airports_to_google.py ran and
its matches were reviewed — and writes code -> place id.

Only the ids are exported. Google's terms let a place id be stored
indefinitely, but not the rest of its content (address, photos), which may only
be cached for a limited time. So a new server fetches those itself:
scripts/link_airports_to_google.py fills them in for every airport the seed
gave an id to.
"""
from __future__ import annotations

import datetime as dt
from pathlib import Path

from sqlalchemy import select

from app.db import SessionLocal
from app.models import Place

OUTPUT = Path(__file__).resolve().parent.parent / "app" / "seeds" / "_airport_google_ids.py"


def main() -> None:
    with SessionLocal() as session:
        rows = session.execute(
            select(Place.code, Place.google_place_id)
            .where(
                Place.category == "airport",
                Place.code.is_not(None),
                Place.google_place_id.is_not(None),
            )
            .order_by(Place.code)
        ).all()

    lines = [
        '"""Generated by scripts/export_airport_google_ids.py — do not edit by hand.',
        "",
        f"The Google place id of {len(rows)} seeded airports, by IATA code, as matched",
        "and reviewed with scripts/link_airports_to_google.py. Ids only: Google's",
        "terms allow storing a place id indefinitely, not its other content.",
        f"Generated {dt.date.today().isoformat()}.",
        '"""',
        "",
        "GOOGLE_PLACE_IDS: dict[str, str] = {",
    ]
    lines += [f"    {code!r}: {place_id!r}," for code, place_id in rows]
    lines += ["}", ""]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(rows)} airport place ids to {OUTPUT}")


if __name__ == "__main__":
    main()
