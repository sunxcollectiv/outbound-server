"""Generate app/seeds/_airports_data.py — the airport seed list.

Run with the two build-time tools available (neither is a runtime dependency):

    uv run --with geonamescache --with timezonefinder python scripts/generate_airports.py

The source is OurAirports (https://ourairports.com/data/, public domain), whose
airports.csv is regenerated nightly. Without --csv the script downloads the
current file; pass --csv to build from a copy you already have.

What is kept: every row with an IATA code AND scheduled commercial service —
the airports people actually book flights through, about 4,000 of OurAirports'
~86,000 rows. That includes the heliports and seaplane bases with scheduled
service (Greenland's settlements, the Maldives), since they appear on tickets
like any other airport. Airfields without scheduled service are left out; an
import that meets one still creates its place on the fly.

OurAirports has no timezone, so each airport's IANA zone is derived from its
coordinates with timezonefinder. Countries are written with OUR area names
(app.seeds.countries) wherever we seed that country, so the seed can link an
airport to its area by name.
"""
from __future__ import annotations

import argparse
import csv
import datetime as dt
import io
import urllib.request
from pathlib import Path

import geonamescache
from timezonefinder import TimezoneFinder

from app.seeds.countries import COUNTRIES, TERRITORIES

SOURCE_URL = "https://davidmegginson.github.io/ourairports-data/airports.csv"
OUTPUT = Path(__file__).resolve().parent.parent / "app" / "seeds" / "_airports_data.py"

# ISO country code -> our area name, where geonames names it differently.
COUNTRY_NAME_OVERRIDES = {
    "CV": "Cape Verde",
    "CW": "Curaçao",
    "CZ": "Czech Republic",
    "MO": "Macau",
    "NL": "Netherlands",
    "TL": "East Timor",
    # Not one of our areas; just a tidier name than geonames' for the address.
    "BQ": "Caribbean Netherlands",
}


def _read_rows(csv_path: Path | None) -> list[dict[str, str]]:
    if csv_path is not None:
        text = csv_path.read_text(encoding="utf-8")
    else:
        with urllib.request.urlopen(SOURCE_URL, timeout=60) as response:
            text = response.read().decode("utf-8")
    return list(csv.DictReader(io.StringIO(text)))


def build(rows: list[dict[str, str]]) -> tuple[list[tuple], list[str]]:
    """The seed entries, sorted by code, plus the country names used that are
    not areas we seed (reported so a missing override is easy to spot)."""
    geonames = geonamescache.GeonamesCache().get_countries()
    ours = {name.casefold() for name in COUNTRIES + TERRITORIES}
    finder = TimezoneFinder()

    entries: dict[str, tuple] = {}
    not_areas: set[str] = set()
    for row in rows:
        code = row["iata_code"].strip().upper()
        if not code or row["scheduled_service"] != "yes" or row["type"] == "closed":
            continue
        if code in entries:
            raise SystemExit(f"IATA code {code} appears twice among scheduled airports")

        iso = row["iso_country"]
        country = COUNTRY_NAME_OVERRIDES.get(iso) or (geonames.get(iso) or {}).get("name")
        country = country.strip() if country else None
        if country and country.casefold() not in ours:
            not_areas.add(country)

        latitude = round(float(row["latitude_deg"]), 5)
        longitude = round(float(row["longitude_deg"]), 5)
        entries[code] = (
            code,
            row["name"].strip(),
            row["municipality"].strip() or None,
            country,
            latitude,
            longitude,
            finder.timezone_at(lat=latitude, lng=longitude),
        )
    return [entries[code] for code in sorted(entries)], sorted(not_areas)


def render(entries: list[tuple]) -> str:
    lines = [
        '"""Generated by scripts/generate_airports.py — do not edit by hand.',
        "",
        f"{len(entries)} airports with an IATA code and scheduled commercial service,",
        "from OurAirports (public domain), as",
        "(code, name, city, country, latitude, longitude, timezone) tuples. Country",
        "names match app.seeds.countries where we seed that country. Regenerate with:",
        "    uv run --with geonamescache --with timezonefinder python scripts/generate_airports.py",
        f"Generated {dt.date.today().isoformat()}.",
        '"""',
        "",
        "AIRPORTS: list[",
        "    tuple[str, str, str | None, str | None, float, float, str | None]",
        "] = [",
    ]
    lines += [f"    {entry!r}," for entry in entries]
    lines += ["]", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate the airport seed list.")
    parser.add_argument(
        "--csv",
        type=Path,
        help="An OurAirports airports.csv to build from. Downloaded when omitted.",
    )
    args = parser.parse_args()

    entries, not_areas = build(_read_rows(args.csv))
    OUTPUT.write_text(render(entries), encoding="utf-8")

    print(f"Wrote {len(entries)} airports to {OUTPUT}")
    print(f"Without a timezone: {sum(1 for e in entries if e[6] is None)}")
    print(f"Without a city: {sum(1 for e in entries if e[2] is None)}")
    print(f"Countries that are not seeded areas ({len(not_areas)}): {', '.join(not_areas)}")


if __name__ == "__main__":
    main()
